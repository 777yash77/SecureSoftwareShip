from __future__ import annotations

import subprocess
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

# Comprehensive standard list of sensitive credential and secret patterns
DEFAULT_PROTECTED_PATTERNS = [
    # Environment & Configuration Secrets
    ".env",
    ".env.*",
    "*.env",
    ".env.local",
    ".env.development",
    ".env.test",
    ".env.production",
    ".env.staging",
    # Database Credentials & Local Data Stores
    "*.db",
    "*.sqlite",
    "*.sqlite3",
    "secureship.db",
    "database.sqlite",
    # Cloud, OAuth, and API Credentials
    "credentials.json",
    "service_account.json",
    "service-account*.json",
    "client_secret*.json",
    "gcp-credentials*.json",
    "aws_credentials",
    ".aws/",
    # Certificates, Tokens, and Private Keys
    "*.pem",
    "*.key",
    "*.pkcs12",
    "*.pfx",
    "*.p12",
    "id_rsa",
    "id_rsa.pub",
    "id_ed25519",
    "id_ecdsa",
    # Local SecureShip tokens and audit cache
    "*.token",
    ".secureship/",
    ".secureshiprc",
]


class SecretProtector:
    """Automated Git immunization engine: protects .env, database credentials, and secret files by managing .gitignore."""

    HEADER_MARKER = "# [SecureShip Auto-Protected Secrets & Credentials]"

    def __init__(self, target_path: Optional[str] = None):
        self.target_path = Path(target_path).resolve() if target_path else Path.cwd()

    def get_existing_patterns(self, gitignore_path: Path) -> Set[str]:
        """Reads and normalizes existing lines from .gitignore."""
        if not gitignore_path.exists():
            return set()
        try:
            content = gitignore_path.read_text(encoding="utf-8", errors="replace")
            patterns = set()
            for line in content.splitlines():
                line = line.strip()
                if line and not line.startswith("#"):
                    patterns.add(line)
            return patterns
        except Exception:
            return set()

    def find_staged_sensitive_files(self, repo_dir: Path) -> List[str]:
        """Queries git to see if any protected sensitive files are currently staged in index."""
        try:
            cmd = ["git", "-C", str(repo_dir), "diff", "--name-only", "--cached"]
            res = subprocess.run(cmd, capture_output=True, text=True, check=False)
            if res.returncode != 0:
                return []

            staged_files = [f.strip() for f in res.stdout.splitlines() if f.strip()]
            sensitive_staged = []

            for sf in staged_files:
                name = Path(sf).name.lower()
                ext = Path(sf).suffix.lower()
                if (
                    name.startswith(".env")
                    or name.endswith(".env")
                    or ext in (".pem", ".key", ".pfx", ".p12", ".db", ".sqlite", ".sqlite3")
                    or "credential" in name
                    or "secret" in name
                    or name in ("id_rsa", "id_ed25519", "secureship.db")
                ):
                    sensitive_staged.append(sf)

            return sensitive_staged
        except Exception:
            return []

    def unstage_files(self, repo_dir: Path, files: List[str]) -> List[str]:
        """Safely removes sensitive files from Git staging area (git rm --cached) without deleting local files."""
        unstaged = []
        for f in files:
            try:
                cmd = ["git", "-C", str(repo_dir), "rm", "--cached", "-f", f]
                res = subprocess.run(cmd, capture_output=True, text=True, check=False)
                if res.returncode == 0:
                    unstaged.append(f)
            except Exception:
                pass
        return unstaged

    def protect(
        self,
        target_dir: Optional[Path] = None,
        auto_unstage: bool = True,
        patterns: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Ensures .gitignore exists and contains all essential sensitive secret and database credential patterns."""
        root = (target_dir or self.target_path).resolve()
        gitignore_path = root / ".gitignore"
        protected_list = patterns or DEFAULT_PROTECTED_PATTERNS

        existing = self.get_existing_patterns(gitignore_path)
        missing = [p for p in protected_list if p not in existing]

        patterns_added: List[str] = []
        if missing:
            block = []
            if not gitignore_path.exists():
                block.append(self.HEADER_MARKER)
                block.append("# Automatically generated by SecureShip to prevent credential leakage to remote Git")
                block.extend(missing)
                gitignore_path.write_text("\n".join(block) + "\n", encoding="utf-8")
                patterns_added = missing
            else:
                existing_text = gitignore_path.read_text(encoding="utf-8", errors="replace")
                needs_header = self.HEADER_MARKER not in existing_text
                block = []
                if existing_text and not existing_text.endswith("\n"):
                    block.append("")
                if needs_header:
                    block.append(self.HEADER_MARKER)
                    block.append("# Automatically generated by SecureShip to prevent credential leakage to remote Git")
                block.extend(missing)
                new_text = existing_text + "\n".join(block) + "\n"
                gitignore_path.write_text(new_text, encoding="utf-8")
                patterns_added = missing

        # Check for staged sensitive files and unstage them if git repository
        files_unstaged: List[str] = []
        git_dir = root / ".git"
        if git_dir.exists() and auto_unstage:
            staged = self.find_staged_sensitive_files(root)
            if staged:
                files_unstaged = self.unstage_files(root, staged)

        # Detect any existing matching files on disk in the repo
        existing_matches = []
        for p in root.glob("*"):
            name = p.name.lower()
            if (
                name.startswith(".env")
                or name.endswith(".db")
                or name.endswith(".sqlite")
                or "credential" in name
                or p.suffix.lower() in (".pem", ".key")
            ):
                existing_matches.append(p.name)

        return {
            "gitignore_path": str(gitignore_path),
            "patterns_added": patterns_added,
            "missing_count": len(patterns_added),
            "files_unstaged": files_unstaged,
            "detected_sensitive_files": sorted(list(set(existing_matches))),
            "status": "PROTECTED",
        }
